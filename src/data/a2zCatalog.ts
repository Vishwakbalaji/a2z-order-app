/**
 * Turns a printed description into name + size/case part without changing a character:
 * "COKE CAN 12OZ 2/12CT" -> name "COKE CAN", variation "12OZ 2/12CT".
 * When the description doesn't end in a size/case part, the whole text is the name.
 */
export function splitDescription(desc: string): { name: string; variation: string } {
  const unit = '(?:[\\d.][^\\s]*|CT|OZ|FL|PK|PACK|ML|L|LTR|GAL|GALLON|G|GR|GM)';
  const m = desc.match(new RegExp(`^(.*?\\S)\\s(${unit}(?:\\s${unit})*)$`, 'i'));
  if (m && /\d/.test(m[2]) && `${m[1]} ${m[2]}` === desc) return { name: m[1], variation: m[2] };
  return { name: desc, variation: '' };
}

/** Brand for a catalog group (the group column is the brand, except the generic "BEVERAGE" cell). */
export function brandForGroup(group: string, desc: string): string {
  if (group === 'BEVERAGE') return desc.split(' ')[0]; // "DOLE PINEAPPLE JUICE 8.4OZ 24CT"
  if (group === 'Plastic bags') return ''; // a product type, not a brand (kept as the category)
  return group;
}
